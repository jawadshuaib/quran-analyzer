#!/usr/bin/env node
/**
 * Write roots/backend/dictionary_guides_meta.py from the guide files, so the
 * backend can serve per-guide <title>/description, crawler <noscript> text and
 * sitemap entries without reading frontend sources (the Docker image ships
 * only backend *.py files).
 *
 *   node scripts/export-dictionary-guide-meta.mjs
 *
 * Re-run whenever a guide's title, author, period, summary or lede changes.
 */
import { build } from 'esbuild';
import { readdirSync, writeFileSync, mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, dirname, basename } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const GUIDE_DIR = join(HERE, '..', 'src', 'content', 'dictionary-guides', 'guides');
const OUT = join(HERE, '..', '..', 'backend', 'dictionary_guides_meta.py');
const TMP = mkdtempSync(join(tmpdir(), 'guide-meta-'));

async function load(file) {
  const res = await build({ entryPoints: [file], bundle: true, format: 'esm', platform: 'node', write: false, logLevel: 'silent' });
  const out = join(TMP, basename(file, '.ts') + '.mjs');
  writeFileSync(out, res.outputFiles[0].text);
  return (await import(pathToFileURL(out).href)).default;
}

function plain(text) {
  return (text || '')
    .replace(/^:::excerpt[\s\S]*?^:::[ \t]*$/gm, '')
    .replace(/\[\[root:[^\]|]*\|[^\]|]*\|([^\]]*)\]\]/g, '$1')
    .replace(/\[\[guide:[^\]|]*\|([^\]]*)\]\]/g, '$1')
    .replace(/\[\^[^\]]*\]/g, '')
    .replace(/\*\*([^*]+)\*\*/g, '$1')
    .replace(/\*([^*\n]+)\*/g, '$1')
    .replace(/^#+\s+/gm, '')
    .replace(/^>\s?/gm, '')
    .replace(/\s+/g, ' ')
    .trim();
}

const py = (s) => JSON.stringify(s ?? null).replace(/\bnull\b/g, 'None');

const files = readdirSync(GUIDE_DIR).filter((f) => f.endsWith('.ts')).map((f) => join(GUIDE_DIR, f));
const guides = [];
for (const f of files) guides.push(await load(f));
guides.sort((a, b) => a.sortYear - b.sortYear || a.title.localeCompare(b.title));

const rows = guides.map((g) => `    {
        "slug": ${py(g.slug)},
        "title": ${py(g.title)},
        "title_ar": ${py(g.titleAr ?? null)},
        "author": ${py(g.author)},
        "period": ${py(g.period)},
        "kind": ${py(g.kind)},
        "summary": ${py(plain(g.summary))},
        "lede": ${py(plain(g.lede))},
    },`);

writeFileSync(
  OUT,
  `"""Reader's guides to the classical dictionaries (/classical-dictionaries).

GENERATED by roots/frontend/scripts/export-dictionary-guide-meta.mjs from
roots/frontend/src/content/dictionary-guides/guides/*.ts — do not edit by hand.
Used for server-rendered SEO meta, crawler <noscript> text and the sitemap.
"""

GUIDES = [
${rows.join('\n')}
]

GUIDES_BY_SLUG = {g["slug"]: g for g in GUIDES}
`,
);
console.log(`wrote ${guides.length} guides to ${OUT}`);
